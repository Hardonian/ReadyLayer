/**
 * Test Execution E2E Tests
 *
 * Tests the complete flow:
 * - Test generation from source code
 * - Test execution in isolated environments
 * - Coverage measurement
 * - Threshold enforcement
 */

import { test, expect } from '@playwright/test';
import { executeTests } from '../services/test-engine/executor';
import { testEngineService, type TestConfig, type TestGenerationRequest } from '../services/test-engine';
import { calculateLLMCost } from '../lib/telemetry/llm-costs';

test.describe('Test Generation and Execution', () => {
  test('should generate tests for JavaScript file', async () => {
    const sourceCode = `
export function add(a, b) {
  return a + b;
}

export function subtract(a, b) {
  return a - b;
}
    `;

    const result = await testEngineService.generateTests({
      repositoryId: 'test-repo-123',
      filePath: 'src/math.js',
      fileContent: sourceCode,
      framework: 'jest',
      config: {
        coverageThreshold: 80,
        failOnBelow: true,
        metric: 'lines',
        enforceOn: 'pr',
        placement: 'co-located',
      },
    });

    expect(result.status).toBe('generated');
    expect(result.framework).toBe('jest');
    expect(result.testContent).toContain('add');
    expect(result.testContent).toContain('test');
  });

  test('should execute Jest tests and measure coverage', async () => {
    const testContent = `
const { add, subtract } = require('./math');

describe('Math functions', () => {
  test('adds numbers', () => {
    expect(add(2, 3)).toBe(5);
    expect(add(0, 0)).toBe(0);
  });

  test('subtracts numbers', () => {
    expect(subtract(5, 3)).toBe(2);
    expect(subtract(0, 0)).toBe(0);
  });
});
    `;

    const sourceCode = `
function add(a, b) {
  return a + b;
}

function subtract(a, b) {
  return a - b;
}

module.exports = { add, subtract };
    `;

    const result = await executeTests({
      filePath: 'src/math.js',
      testContent,
      sourceCode,
      framework: 'jest',
      coverageThreshold: 80,
    });

    expect(result.status).toMatch(/passed|failed/);
    expect(result.testsPassed).toBeGreaterThanOrEqual(0);
    expect(result.totalTests).toBeGreaterThanOrEqual(0);
    expect(result.durationMs).toBeGreaterThan(0);
    expect(result.coverage.lines.percentage).toBeLessThanOrEqual(100);
  });

  test('should handle test timeout', async () => {
    const slowTestContent = `
describe('Slow tests', () => {
  test('timeout test', async () => {
    await new Promise(resolve => setTimeout(resolve, 60000));
  });
});
    `;

    const result = await executeTests(
      {
        filePath: 'src/slow.js',
        testContent: slowTestContent,
        sourceCode: 'const x = 1;',
        framework: 'jest',
        coverageThreshold: 80,
      },
      1000 // 1 second timeout
    );

    expect(result.status).toBe('timeout');
  });

  test('should detect AI-touched files', async () => {
    const files = [
      {
        path: 'src/generated.js',
        content: 'export function test() { } // Generated by Copilot',
        commitMessage: 'Add generated file by AI',
      },
      {
        path: 'src/manual.js',
        content: 'export function test() { }',
        commitMessage: 'Add manual file',
      },
    ];

    const aiFiles = await testEngineService.detectAITouchedFiles('repo-123', files);

    expect(aiFiles.length).toBeGreaterThan(0);
    expect(aiFiles[0].path).toContain('generated');
    expect(aiFiles[0].confidence).toBeGreaterThan(0.5);
  });

  test('should enforce coverage threshold', async () => {
    const testContent = `
describe('Coverage test', () => {
  test('covers branch a', () => {
    expect(true).toBe(true);
  });
});
    `;

    const sourceCode = `
function test(condition) {
  if (condition) {
    return 'a';
  } else {
    return 'b';  // Not covered
  }
}
    `;

    const result = await executeTests({
      filePath: 'src/test.js',
      testContent,
      sourceCode,
      framework: 'jest',
      coverageThreshold: 80,
    });

    // Coverage is likely below 80%
    expect(result.meetsThreshold).toBeDefined();
  });

  test('should calculate LLM costs correctly', () => {
    // GPT-4 Turbo: $0.01 per 1K input, $0.03 per 1K output
    const cost = calculateLLMCost('openai', 'gpt-4-turbo', 1000, 1000);
    expect(cost).toBe(0.04); // 0.01 + 0.03

    // Claude 3 Haiku: $0.00025 per 1K input, $0.00125 per 1K output
    const haikuCost = calculateLLMCost('anthropic', 'claude-3-haiku', 1000, 1000);
    expect(haikuCost).toBeCloseTo(0.0015);

    // GPT-3.5 Turbo (cheaper): $0.0005 + $0.0015 = $0.002
    const gpt35Cost = calculateLLMCost('openai', 'gpt-3.5-turbo', 1000, 1000);
    expect(gpt35Cost).toBeCloseTo(0.002);
  });

  test('should track multiple test frameworks', async () => {
    const frameworks: Array<TestGenerationRequest['framework']> = ['jest', 'mocha', 'pytest', 'vitest'];

    for (const framework of frameworks) {
      const result = await testEngineService.generateTests({
        repositoryId: 'test-repo-123',
        filePath: `src/test.${framework === 'pytest' ? 'py' : 'js'}`,
        fileContent: 'export function test() { return true; }',
        framework: framework,
      });

      expect(result).toBeDefined();
      expect(result.framework).toBe(framework);
    }
  });

  test('should generate deterministic tests', async () => {
    const sourceCode = `
export function sum(arr) {
  return arr.reduce((a, b) => a + b, 0);
}
    `;

    // Generate twice with same input
    const result1 = await testEngineService.generateTests({
      repositoryId: 'test-repo-123',
      filePath: 'src/sum.js',
      fileContent: sourceCode,
      framework: 'jest',
    });

    const result2 = await testEngineService.generateTests({
      repositoryId: 'test-repo-123',
      filePath: 'src/sum.js',
      fileContent: sourceCode,
      framework: 'jest',
    });

    // Same inputs should produce same or very similar tests
    expect(result1.testContent).toBeDefined();
    expect(result2.testContent).toBeDefined();
  });

  test('should handle test syntax errors gracefully', async () => {
    const invalidTestContent = `
describe('Invalid syntax', () => {
  test('broken test' () => { // Missing comma
    expect(true).toBe(true);
  });
});
    `;

    const result = await executeTests({
      filePath: 'src/invalid.js',
      testContent: invalidTestContent,
      sourceCode: 'const x = 1;',
      framework: 'jest',
      coverageThreshold: 80,
    });

    // Should fail gracefully
    expect(result.status).toBe('failed');
    expect(result.error).toBeDefined();
  });

  test('should measure coverage across multiple files', async () => {
    const files = [
      {
        filePath: 'src/file1.js',
        testContent: 'test("file1", () => { expect(true).toBe(true); });',
        sourceCode: 'export function fn1() { return true; }',
      },
      {
        filePath: 'src/file2.js',
        testContent: 'test("file2", () => { expect(true).toBe(true); });',
        sourceCode: 'export function fn2() { return false; }',
      },
    ];

    for (const file of files) {
      const result = await executeTests({
        filePath: file.filePath,
        testContent: file.testContent,
        sourceCode: file.sourceCode,
        framework: 'jest',
        coverageThreshold: 50,
      });

      expect(result.durationMs).toBeGreaterThan(0);
    }
  });

  test('should respect test placement strategy', async () => {
    const placements: Array<TestConfig['placement']> = ['co-located', 'separate', 'mirror'];

    for (const placement of placements) {
      const result = await testEngineService.generateTests({
        repositoryId: 'test-repo-123',
        filePath: 'src/lib/utils.js',
        fileContent: 'export function util() { return 42; }',
        framework: 'jest',
        config: {
          coverageThreshold: 80,
          failOnBelow: true,
          metric: 'lines',
          enforceOn: 'pr',
          placement: placement,
        },
      });

      expect(result).toBeDefined();
      // Verify placement logic
      if (placement === 'co-located') {
        expect(result.placement).toContain('.test.');
      }
    }
  });
});
